#!/usr/bin/env bash
# Writes the manifest to submit to Flathub: identical to io.github.kingrubic.MiniSnap.yml, except that
# MiniSnap itself is fetched from this repository at a tagged commit (Flathub builds from a git source).
# Usage: make-flathub-manifest.sh <tag> [output]   e.g. make-flathub-manifest.sh v1.7.0 dist/io.github.kingrubic.MiniSnap.yml
set -euo pipefail

TAG="${1:?usage: $0 <tag> [output]}"
OUT="${2:-io.github.kingrubic.MiniSnap.yml}"
HERE="$(cd "$(dirname "$0")" && pwd)"
COMMIT="$(git -C "$HERE" rev-list -n 1 "$TAG")"

python3 - "$HERE/io.github.kingrubic.MiniSnap.yml" "$OUT" "$TAG" "$COMMIT" <<'EOF'
import sys
src, out, tag, commit = sys.argv[1:5]
text = open(src, encoding="utf-8").read()
local = "      - type: dir\n        path: ..\n"
if local not in text:
    sys.exit("could not find the local 'dir' source in the manifest")
git = (
    "      - type: git\n"
    "        url: https://github.com/kingrubic/minisnap.git\n"
    f"        tag: {tag}\n"
    f"        commit: {commit}\n"
)
text = text.replace(local, git)
# The app lives in the linux/ folder of the repository.
text = text.replace("      - cp -r minisnap /app/share/minisnap/", "      - cp -r linux/minisnap /app/share/minisnap/")
for f in ("bin/minisnap", "data/io.github.kingrubic.MiniSnap.desktop",
          "data/icons/hicolor/scalable/apps/io.github.kingrubic.MiniSnap.svg",
          "data/io.github.kingrubic.MiniSnap.metainfo.xml"):
    text = text.replace(f" {f} ", f" linux/{f} ")
text = text.replace("# Flatpak manifest for MiniSnap", "# Flathub manifest for MiniSnap (generated by linux/packaging/make-flathub-manifest.sh)")
open(out, "w", encoding="utf-8").write(text)
print(f"wrote {out} for {tag} ({commit})")
EOF
